def read_cstr(fh, off: int) -> bytes:
    fh.seek(MAP_ISO_OFF + off)
    out = bytearray()
    while True:
        byte = fh.read(1)
        if not byte or byte == b"\x00":
            return bytes(out)
        out += byte


