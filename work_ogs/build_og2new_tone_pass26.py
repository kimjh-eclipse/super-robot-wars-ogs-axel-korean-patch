def politenize(text: str) -> str:
    for pattern, replacement in ENDING_RULES:
        text = re.sub(pattern, replacement, text)
    return text


def force_respectful(text: str) -> str:
    for pattern, replacement in FORCE_RESPECTFUL_RULES:
        text = re.sub(pattern, replacement, text)
    return politenize(text)


def transform_lamia(item: dict) -> str:
    text = item["text"]
    flags = set(item["flags"])
    if text == "라미아：떨어지는…가！":
        return "라미아：격추당하는가！"

    if "확정_빈델님_누락" in flags:
        text = replace_name(text, "빈델", "빈델님")
    if "확정_레몬님_누락" in flags:
        text = replace_name(text, "레몬", "레몬님")
    if "확정_액셀대장_누락" in flags:
        text = replace_name(text, "액셀", "액셀　대장")

    # Remove role-swap residue in Lamia's direct speech.
    text = (text.replace("습니다에요", "습니다")
                .replace("합니다에요", "합니다")
                .replace("입니다에요", "입니다")
                .replace("하였습니다인걸", "했습니다")
                .replace("했거나해버렸", "했습니다")
                .replace("해버렸습니다인", "했습니다")
                .replace("겠습니까요", "겠습니까")
                .replace("이옵니다", "입니다")
                .replace("하겠사옵니다", "하겠습니다"))
    if "확정_액셀식구어" in flags:
        text = (text.replace("참말", "정말")
                    .replace("이거구만", "그렇군")
                    .replace("구만", "군")
                    .replace("말이지", "말입니다")
                    .replace("말야", "말입니다")
                    .replace("이거냐", "이겁니까")
                    .replace("뭐야", "뭡니까")
                    .replace("됐냐", "됐습니까"))

    superior = bool(flags.intersection({
        "확정_상관응답_비경어", "확정_액셀응답_비경어",
        "확정_빈델님_누락", "확정_레몬님_누락", "확정_액셀대장_누락",
    }))
    if superior and text.startswith("라미아："):
        text = force_respectful(text)
    return text


