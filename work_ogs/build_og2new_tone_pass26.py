def fit_candidate(text: str, capacity: int) -> str:
    """Keep wording intact while reclaiming harmless display-width bytes."""
    if len(encode(text)) <= capacity:
        return text
    # Fullwidth spaces are conventional but an ASCII space remains visible and
    # is one byte cheaper in this codec.  Convert only as many as required.
    chars = list(text)
    for index in range(len(chars) - 1, -1, -1):
        if chars[index] == "　":
            chars[index] = " "
            candidate = "".join(chars)
            if len(encode(candidate)) <= capacity:
                return candidate
    text = "".join(chars)
    for old, new in (("…………", "……"), ("……", "…"), ("…。", "。"),
                     ("、@", "@"), ("…@", "@")):
        while old in text and len(encode(text)) > capacity:
            text = text.replace(old, new, 1)
    return text


